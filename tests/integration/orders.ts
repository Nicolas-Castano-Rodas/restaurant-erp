import "dotenv/config";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { getPrisma } from "../../src/lib/prisma";
import { createOrder, parseOrderInput, listOrderPage, parseOrderCursor } from "../../src/modules/orders/service";
import { saveCustomer, customerHistory, listPosCustomers } from "../../src/modules/customers/service";
import { saveCourier, assignCourier, advanceDelivery } from "../../src/modules/deliveries/service";
import { payOrder, openShift } from "../../src/modules/cash/service";
import { listTables } from "../../src/modules/catalog/service";

async function main() {
  if (process.env.RUN_DB_TESTS !== "true") throw new Error("Use a disposable database");
  const db = getPrisma();
  const ids = [randomUUID(), randomUUID()];
  const userId = randomUUID();
  try {
    const [a, b] = await Promise.all(ids.map((id) => db.organization.create({ data: { id, name: "Test", slug: id } })));
    const branch = await db.branch.create({ data: { organizationId: a.id, name: "A", code: "A" } });
    const otherBranch = await db.branch.create({ data: { organizationId: b.id, name: "B", code: "B" } });
    const role = await db.role.create({ data: { organizationId: a.id, name: "Test" } });
    await db.permission.upsert({ where: { code: "orders.manage" }, create: { code: "orders.manage", description: "Orders" }, update: {} });
    await db.rolePermission.create({ data: { roleId: role.id, permissionCode: "orders.manage" } });
    await db.user.create({ data: { id: userId, email: `${userId}@example.invalid`, name: "Test" } });
    const membership = await db.membership.create({ data: { organizationId: a.id, userId, roleId: role.id } });
    await db.membershipBranch.create({ data: { organizationId: a.id, membershipId: membership.id, branchId: branch.id } });
    const table = await db.restaurantTable.create({ data: { organizationId: a.id, branchId: branch.id, name: "Mesa 1", capacity: 4 } });
    const otherTable = await db.restaurantTable.create({ data: { organizationId: b.id, branchId: otherBranch.id, name: "Mesa 2", capacity: 4 } });
    const category = await db.category.create({ data: { organizationId: a.id, name: "Test" } });
    const product = await db.product.create({ data: { organizationId: a.id, categoryId: category.id, name: "Arroz", price: "12500.50" } });
    const variant = await db.productVariant.create({ data: { organizationId: a.id, productId: product.id, name: "Grande", price: "18000.25" } });
    const scope = { organizationId: a.id, branchId: branch.id, membershipId: membership.id };
    const customer = await saveCustomer(db, scope, { name: "Cliente de prueba", phone: "3000000000", email: "", active: true });
    const foreign = await db.customer.create({ data: { organizationId: b.id, branchId: otherBranch.id, name: "Other" } });
    assert.equal((await listPosCustomers(db, a.id, branch.id)).length, 1);
    const input = parseOrderInput({ requestId: randomUUID(), channel: "DINE_IN", tableId: table.id, customerId: customer.id, note: "", items: [{ productId: product.id, variantId: variant.id, quantity: 3, price: "1" }] });
    await assert.rejects(createOrder(db, scope, { ...input, customerId: foreign.id }), /Cliente no disponible/);
    const id = await createOrder(db, scope, input);
    assert.equal(await createOrder(db, scope, input), id);
    const order = await db.order.findUniqueOrThrow({ where: { id }, include: { lines: true } });
    assert.equal(order.total.toFixed(2), "54000.75");
    assert.equal(order.customerId, customer.id);
    assert.equal((await customerHistory(db, a.id, branch.id, customer.id))?.orders.length, 1);
    assert.equal((await customerHistory(db, a.id, branch.id, customer.id))?.paid.length, 0);
    assert.equal(await customerHistory(db, a.id, branch.id, foreign.id), null);
    assert.equal(order.lines[0].productName, "Arroz");
    assert.equal((await listTables(db, a.id, branch.id))[0].occupied, true);
    await assert.rejects(createOrder(db, scope, { ...input, requestId: randomUUID() }), /pedido abierto/);
    await assert.rejects(createOrder(db, scope, { ...input, requestId: randomUUID(), tableId: otherTable.id }), /Mesa no disponible/);
    await assert.rejects(createOrder(db, scope, { ...input, note: "changed" }), /solicitud ya fue utilizada/);
    await saveCustomer(db, scope, { id: customer.id, name: "Cliente de prueba", phone: "", email: "", active: false });
    await assert.rejects(createOrder(db, scope, { ...input, requestId: randomUUID(), channel: "TAKEAWAY", tableId: null }), /Cliente no disponible/);
    await saveCustomer(db, scope, { id: customer.id, name: "Cliente de prueba", phone: "", email: "", active: true });
    const anonymous = await createOrder(db, scope, { ...input, customerId: null, requestId: randomUUID(), channel: "TAKEAWAY", tableId: null });
    assert.equal((await db.order.findUniqueOrThrow({ where: { id: anonymous } })).customerId, null);
    const deliveryInput = { ...input, requestId: randomUUID(), channel: "DELIVERY" as const, tableId: null, delivery: { recipient: "Test", phone: "3000000000", address: "Dirección ficticia", instructions: "", fee: "3500.50" } };
    const deliveryOrder = await createOrder(db, scope, deliveryInput);
    assert.equal(await createOrder(db, scope, deliveryInput), deliveryOrder);
    const deliveredOrder = await db.order.findUniqueOrThrow({ where: { id: deliveryOrder }, include: { delivery: true } });
    assert.equal(deliveredOrder.total.toFixed(2), "57501.25");
    assert.equal(deliveredOrder.deliveryFee.toFixed(2), "3500.50");
    assert.ok(deliveredOrder.delivery);
    const deliveryId = deliveredOrder.delivery.id;
    const courier = await saveCourier(db, scope, { name: "Test courier", phone: "", active: true });
    const otherCourier = await db.courier.create({ data: { organizationId: b.id, branchId: otherBranch.id, name: "Other" } });
    await assert.rejects(assignCourier(db, scope, deliveryId, otherCourier.id), /no disponible/);
    await assignCourier(db, scope, deliveryId, courier.id);
    await assert.rejects(advanceDelivery(db, scope, deliveryId, "DELIVERED"), /estado/);
    await assert.rejects(advanceDelivery(db, scope, deliveryId, "DISPATCHED"), /cocina/);
    await db.order.update({ where: { id: deliveryOrder }, data: { kitchenStatus: "SERVED" } });
    await db.permission.upsert({ where: { code: "cash.manage" }, create: { code: "cash.manage", description: "Cash" }, update: {} });
    await db.rolePermission.create({ data: { roleId: role.id, permissionCode: "cash.manage" } });
    await openShift(db, scope, "0");
    await assert.rejects(payOrder(db, scope, deliveryOrder, "CASH", "60000"), /domicilio/);
    await advanceDelivery(db, scope, deliveryId, "DISPATCHED");
    await advanceDelivery(db, scope, deliveryId, "DELIVERED");
    const payment = await payOrder(db, scope, deliveryOrder, "CASH", "60000");
    assert.equal(payment.amount.toFixed(2), "57501.25");
    // Force equal timestamps to exercise the stable UUID tiebreaker.
    const stamp = new Date("2026-11-25T00:00:00.000Z");
    await db.order.createMany({ data: Array.from({ length: 53 }, () => ({ organizationId: a.id, branchId: branch.id, membershipId: scope.membershipId, requestId: randomUUID(), requestHash: "f".repeat(64), channel: "TAKEAWAY" as const, currency: "COP", subtotal: "0", total: "0", createdAt: stamp })) });
    const first = await listOrderPage(db, a.id, branch.id);
    assert.equal(first.orders.length, 50);
    assert.ok(first.nextCursor);
    const next = parseOrderCursor(first.nextCursor);
    assert.ok(next);
    const secondPage = await listOrderPage(db, a.id, branch.id, next);
    assert.equal(secondPage.nextCursor, null);
    assert.equal(first.orders.length + secondPage.orders.length, await db.order.count({ where: { organizationId: a.id, branchId: branch.id } }));
    assert.equal(new Set([...first.orders, ...secondPage.orders].map((entry) => entry.id)).size, first.orders.length + secondPage.orders.length);
    assert.equal((await listOrderPage(db, b.id, otherBranch.id, next)).orders.length, 0);
    assert.equal(parseOrderCursor("invalid"), undefined);
    await db.product.update({ where: { id: product.id }, data: { name: "Changed", available: false } });
    assert.equal((await db.orderLine.findFirstOrThrow({ where: { orderId: id } })).productName, "Arroz");
    await assert.rejects(createOrder(db, scope, { ...input, requestId: randomUUID(), channel: "TAKEAWAY", tableId: null }), /ya no está disponible/);
    await assert.rejects(createOrder(db, { ...scope, branchId: otherBranch.id }, input), /autorización/);
    console.log("POS order integrity checks passed.");
  } finally {
    try {
      const where = { organizationId: { in: ids } };
      await db.payment.deleteMany({ where });
      await db.cashShift.deleteMany({ where });
      await db.delivery.deleteMany({ where });
      await db.courier.deleteMany({ where });
      await db.orderLine.deleteMany({ where });
      await db.order.deleteMany({ where });
      await db.customer.deleteMany({ where });
      await db.restaurantTable.deleteMany({ where });
      await db.productVariant.deleteMany({ where });
      await db.product.deleteMany({ where });
      await db.category.deleteMany({ where });
      await db.membershipBranch.deleteMany({ where });
      await db.auditEvent.deleteMany({ where });
      await db.membership.deleteMany({ where });
      await db.role.deleteMany({ where });
      await db.user.deleteMany({ where: { id: userId } });
      await db.branch.deleteMany({ where });
      await db.organization.deleteMany({ where: { id: { in: ids } } });
    } finally { await db.$disconnect(); }
  }
}
main().catch((error: unknown) => { console.error(error); process.exitCode = 1; });
